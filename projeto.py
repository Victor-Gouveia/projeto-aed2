# 1. Configurando os caminhos dos arquivos gerados pelo scraping
pasta_dados = "dataset"  # Ou "dados_emuladores", conforme a pasta gerada pelo script

caminho_edges = f"{pasta_dados}/emu_git_edges.csv"
